-- Safe additive migration: does not alter or delete existing portal tables.
create table if not exists public.hub_users (
 id bigint generated by default as identity primary key,
 auth_id uuid unique not null references auth.users(id) on delete cascade,
 username text not null unique,
 display_name text not null,
 role text not null default 'coordinador' check (role in ('administrador','gerente','coordinador')),
 active boolean not null default true,
 access jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
create table if not exists public.hub_records (
 id bigint generated by default as identity primary key,
 kind text not null check(kind in ('profile','schedule','run','tracking','settings','audit')),
 payload jsonb not null default '{}'::jsonb,
 created_by bigint references public.hub_users(id) on delete set null,
 created_at timestamptz not null default now()
);
create index if not exists hub_records_kind_id on public.hub_records(kind,id desc);
create table if not exists public.hub_tariff_rows (
 id bigint generated by default as identity primary key,
 payer text not null,
 profat text not null,
 description text not null,
 amount numeric(14,2) not null check (amount >= 0),
 group_name text not null default '',
 group_num text not null default '',
 segus text not null default '',
 vigencia text not null default '',
 updated_at timestamptz not null default now(),
 unique(payer,profat)
);
create index if not exists hub_tariff_payer on public.hub_tariff_rows(payer);
create table if not exists public.hub_tariff_imports (
 id bigint generated by default as identity primary key,
 payer text not null,
 mode text not null,
 file_name text,
 record_count integer not null,
 imported_by bigint references public.hub_users(id) on delete set null,
 imported_at timestamptz default now()
);
-- All writes/reads from the browser are blocked. Only server-side service-role
-- requests validated against Supabase Auth may access these tables.
alter table public.hub_users enable row level security;
alter table public.hub_records enable row level security;
alter table public.hub_tariff_rows enable row level security;
alter table public.hub_tariff_imports enable row level security;
revoke all on public.hub_users from anon, authenticated;
revoke all on public.hub_records from anon, authenticated;
revoke all on public.hub_tariff_rows from anon, authenticated;
revoke all on public.hub_tariff_imports from anon, authenticated;

-- Foto opcional guardada como imagen pequeña comprimida (acceso solo por servidor).
alter table public.hub_users add column if not exists avatar_data text;

create table if not exists public.hub_exp_snapshots (
 date text primary key check (date ~ '^\d{4}-\d{2}-\d{2}$'),
 payload jsonb not null,
 updated_by bigint references public.hub_users(id) on delete set null,
 updated_at timestamptz not null default now()
);
alter table public.hub_exp_snapshots enable row level security;
revoke all on public.hub_exp_snapshots from anon, authenticated;

-- Transacciones atómicas para nuevas reglas y actualizaciones; respaldo previo en Supabase.
create table if not exists public.hub_tariff_revisions (
 id bigint generated by default as identity primary key,
 payer text not null, mode text not null, file_name text,
 previous_rows jsonb not null default '[]'::jsonb,
 new_count integer not null,
 created_by bigint references public.hub_users(id) on delete set null,
 created_at timestamptz not null default now()
);
alter table public.hub_tariff_revisions enable row level security;
revoke all on public.hub_tariff_revisions from anon, authenticated;

create or replace function public.hub_replace_tariff(
 p_payer text, p_mode text, p_file text, p_rows jsonb, p_user bigint
) returns jsonb language plpgsql security definer set search_path = public as $$
declare n integer; existing boolean; backup_id bigint;
begin
 if p_payer is null or length(trim(p_payer))<1 or length(p_payer)>100 or lower(p_payer)='regla'
    then raise exception 'Nombre de IAFA inválido';end if;
 if p_mode not in ('new','update') then raise exception 'Modo de importación inválido';end if;
 if jsonb_typeof(p_rows) <> 'array' then raise exception 'El archivo no contiene filas';end if;
 n := jsonb_array_length(p_rows);
 if n<1 or n>30000 then raise exception 'Cantidad de filas no permitida';end if;
 if exists (select 1 from jsonb_array_elements(p_rows) x where nullif(trim(x->>'profat'),'') is null or nullif(trim(x->>'description'),'') is null or (x->>'amount') is null)
    then raise exception 'Falta PROFAT, descripción o importe'; end if;
 if exists (select 1 from jsonb_array_elements(p_rows) x where (x->>'amount')::numeric<0 or (x->>'amount')::numeric>=1000000000)
    then raise exception 'Importe fuera del rango';end if;
 if (select count(distinct trim(x->>'profat')) from jsonb_array_elements(p_rows) x) <> n
    then raise exception 'Se encontraron PROFAT duplicados';end if;
 perform pg_advisory_xact_lock(hashtext(p_payer));
 existing := exists(select 1 from public.hub_tariff_rows where payer=p_payer);
 if p_mode='new' and existing then raise exception 'La IAFA ya existe. Usa Actualizar';end if;
 if p_mode='update' and not existing then raise exception 'La IAFA no existe. Usa Nuevo tarifario';end if;
 insert into public.hub_tariff_revisions(payer,mode,file_name,previous_rows,new_count,created_by)
 values (p_payer,p_mode,p_file,
  coalesce((select jsonb_agg(jsonb_build_object('payer',payer,'profat',profat,'description',description,'amount',amount,'group',group_name,'group_num',group_num,'segus',segus,'vigencia',vigencia)) from public.hub_tariff_rows where payer=p_payer),'[]'::jsonb),
  n,p_user)
 returning id into backup_id;
 delete from public.hub_tariff_rows where payer=p_payer;
 insert into public.hub_tariff_rows(payer,profat,description,amount,group_name,group_num,segus,vigencia)
 select p_payer,trim(x.profat),trim(x.description),x.amount,
 coalesce(x.group_name,''),coalesce(x.group_num,''),coalesce(x.segus,''),coalesce(x.vigencia,'')
 from jsonb_to_recordset(p_rows) as x(profat text,description text,amount numeric,group_name text,group_num text,segus text,vigencia text);
 insert into public.hub_tariff_imports(payer,mode,file_name,record_count,imported_by)
 values (p_payer,p_mode,p_file,n,p_user);
 return jsonb_build_object('ok',true,'count',n,'payer',p_payer,'backup','Revisión # '||backup_id);
end;$$;
revoke all on function public.hub_replace_tariff(text,text,text,jsonb,bigint) from public,anon,authenticated;
grant execute on function public.hub_replace_tariff(text,text,text,jsonb,bigint) to service_role;
